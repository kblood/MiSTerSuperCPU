def get_size(op, m, x):
    mode = MODES.get(op, 1)
    if mode == 'M':
        return 1 + (2 if m == 0 else 1)
    elif mode == 'X':
        return 1 + (2 if x == 0 else 1)
    else:
        return 1 + mode

def disasm(data, bank, start_pc, m=0, x=0, max_lines=80):
    pc = start_pc
    lines = 0
    while pc - start_pc < len(data) and lines < max_lines:
        idx = pc - start_pc
        op = data[idx]
        name = NAMES.get(op, '???')
        sz = get_size(op, m, x)

        if idx + sz > len(data):
            break

        raw = ' '.join(f'{data[idx+i]:02X}' for i in range(sz))

        # Track M/X
        if op == 0xC2 and idx+1 < len(data):  # REP
            bits = data[idx+1]
            if bits & 0x20: m = 0
            if bits & 0x10: x = 0
        elif op == 0xE2 and idx+1 < len(data):  # SEP
            bits = data[idx+1]
            if bits & 0x20: m = 1
            if bits & 0x10: x = 1
        elif op == 0xFB:  # XCE
            pass  # complex, skip

        print(f'  ${bank:02X}:{pc:04X}  {raw:<14s} {name}')

        pc += sz
        lines += 1

        # Stop at unconditional transfers
        if op in (0x5C, 0x6B, 0x60, 0x40, 0x4C, 0x80, 0xDB, 0xCB):
            if op == 0x5C:
                b = data[idx+3]
                a = data[idx+1] | (data[idx+2] << 8)
                print(f'  --- JML ${b:02X}:${a:04X} ---')
            elif op == 0xDC:
                a = data[idx+1] | (data[idx+2] << 8)
                print(f'  --- JML [${a:04X}] ---')
            break
    return pc, m, x

