void print_clear(void)
{
  unsigned char *dst = (unsigned char *)1024;
  int i;

  for (i = 0; i < (40 * 25); i++)
  {
    dst[i] = ascii_to_screen[' '];
  }

  /* switch to shifted (lowercase) mode */
  dst = (unsigned char *)0xd018;
  *dst |= 0x02;
}

int print_char(int x, int y, const char c)
{
  unsigned char *dst = (unsigned char *)1024;

  dst += (y * 40);
  dst += x;

  dst[0] = ascii_to_screen[(unsigned char)c];
  x++;

  return x;
}

int print_text(int x, int y, const char *text)
{
  unsigned char *dst = (unsigned char *)1024;
  unsigned char *src = (unsigned char *)text;

  dst += (y * 40);
  dst += x;

  while (*src != '\0')
  {
    dst[0] = ascii_to_screen[src[0]];
    dst++;
    src++;
    x++;
  }

  return x;
}

static const unsigned char hex_string[] = "0123456789ABCDEF";

int print_hex(int x, int y, unsigned int hex)
{
  print_char(x + 0, y, '0');
  print_char(x + 1, y, 'x');
  print_char(x + 2, y, hex_string[((hex >> 28) & 0x0f)]);
  print_char(x + 3, y, hex_string[((hex >> 24) & 0x0f)]);
  print_char(x + 4, y, hex_string[((hex >> 20) & 0x0f)]);
  print_char(x + 5, y, hex_string[((hex >> 16) & 0x0f)]);
  print_char(x + 6, y, hex_string[((hex >> 12) & 0x0f)]);
  print_char(x + 7, y, hex_string[((hex >>  8) & 0x0f)]);
  print_char(x + 8, y, hex_string[((hex >>  4) & 0x0f)]);
  print_char(x + 9, y, hex_string[((hex >>  0) & 0x0f)]);
  return x + 10;
}

int print_dec(int x, int y, int dec, int length, int zero_pad)
{
  char buffer[16];
  int i = 0, sign = 0;

  if (dec < 0)
  {
    sign = 1;
    dec = -dec;
  }

  do
  {
    buffer[i] = '0' + (dec % 10);
    i++;
    dec /= 10;
  } while (dec > 0);

  if ((!zero_pad) && (sign))
  {
    buffer[i] = '-';
    i++;
  }

  while (i < length)
  {
    if (zero_pad)
    {
      buffer[i] = '0';
    }
    else
    {
      buffer[i] = ' ';
    }
    i++;
  }

  if ((zero_pad) && (sign))
  {
    i--;
    buffer[i] = '-';
    i++;
  }

  while (i > 0)
  {
    print_char(x, y, buffer[i - 1]);
    x++;
    i--;
  }

  return x;
}
