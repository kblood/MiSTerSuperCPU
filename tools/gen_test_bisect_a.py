#!/usr/bin/env python3
"""Bisect A: include a turbo->1MHz toggle BEFORE the iteration.
If this fails, the bug is in 1MHz/turbo state leaking forward.
Sequence:
  1MHz on
  TURBO ON  <-- NEW
  1MHz ON   <-- NEW (mimics post-long-store of imaginary prev iter)
  FETCH bank $2A
  TURBO ON
  Long-store
  1MHz ON
  Check $2A:$6C00 = $3E
"""
import os
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'test_bisect_a.prg')
basic_stub = bytes([0x0B,0x08,0x0A,0x00,0x9E,0x32,0x30,0x36,0x31,0x00,0x00,0x00])
code = []
def emit(*bs): code.extend(bs)
emit(0x78)
emit(0xA9, 0x35, 0x85, 0x01)
emit(0x8D, 0x7E, 0xD0)               # SCPU regs en
emit(0x8D, 0x7A, 0xD0)               # 1MHz
# Pre-toggle (NEW)
emit(0x8D, 0x7B, 0xD0)               # turbo on
emit(0x8D, 0x7A, 0xD0)               # 1MHz on
emit(0xA9, 0x03, 0x8D, 0x20, 0xD0)   # cyan
# FETCH bank $2A
emit(0xA9, 0x00, 0x8D, 0x02, 0xDF)
emit(0xA9, 0x05, 0x8D, 0x03, 0xDF)
emit(0xA9, 0x00, 0x8D, 0x04, 0xDF)
emit(0xA9, 0x6C, 0x8D, 0x05, 0xDF)
emit(0xA9, 0x2A, 0x8D, 0x06, 0xDF)
emit(0xA9, 0x00, 0x8D, 0x07, 0xDF)
emit(0xA9, 0x01, 0x8D, 0x08, 0xDF)
emit(0xA9, 0x91, 0x8D, 0x01, 0xDF)
# Turbo + long-store
emit(0x8D, 0x7B, 0xD0)
emit(0xA9, 0x00, 0x85, 0xFB)
emit(0xA9, 0x6C, 0x85, 0xFC)
emit(0xA9, 0x2A, 0x85, 0xFD)
emit(0xA9, 0x34, 0x85, 0x01)
emit(0xA0, 0x00)
emit(0xB9, 0x00, 0x05)
emit(0x97, 0xFB)
emit(0xC8)
emit(0xD0, 0xF8)
emit(0xA9, 0x35, 0x85, 0x01)
emit(0x8D, 0x7A, 0xD0)
# Check
emit(0x8D, 0x7B, 0xD0)
emit(0x18, 0xFB)
emit(0xC2, 0x20)
emit(0xAF, 0x00, 0x6C, 0x2A)
emit(0xE2, 0x20)
emit(0xC9, 0x3E)
bne_pos = len(code); emit(0xD0, 0x00)
emit(0xA9, 0x05, 0x8D, 0x20, 0xD0)
pj = len(code); emit(0x4C, 0x00, 0x00)
red = len(code)
emit(0xA9, 0x02, 0x8D, 0x20, 0xD0)
fj = len(code); emit(0x4C, 0x00, 0x00)
code[bne_pos+1] = (red - (bne_pos+2)) & 0xFF
addr = 0x080D + pj; code[pj+1] = addr & 0xFF; code[pj+2] = (addr>>8) & 0xFF
addr = 0x080D + fj; code[fj+1] = addr & 0xFF; code[fj+2] = (addr>>8) & 0xFF
prg = bytes([0x01,0x08]) + basic_stub + bytes(code)
with open(OUT,'wb') as f: f.write(prg)
print('wrote',OUT,len(prg),'bytes')
