#!/usr/bin/env python3
"""Test REU FETCH in 1MHz mode (mimics Doom loader path).

Sequence:
  STA $D07E (SCPU regs en)
  STA $D07A (1MHz mode <-- key)
  REU FETCH REU $2A:$6C00 -> c64 $0500, len 256
  STA $D07B (turbo on for long-store)
  Long-store $0500..$05FF -> bank $2A:$6C00
  STA $D07A (back to 1MHz)
  Native + 16-bit M; LDA long $2A:$6C00; CMP #$3E
  Border green = $3E (PASS), red = something else (FAIL).
"""
import os

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'test_fetch_1mhz.prg')

basic_stub = bytes([
    0x0B, 0x08, 0x0A, 0x00, 0x9E,
    0x32, 0x30, 0x36, 0x31,
    0x00, 0x00, 0x00,
])

code = []
def emit(*bs): code.extend(bs)

emit(0x78)                           # SEI
emit(0xA9, 0x35, 0x85, 0x01)
emit(0x8D, 0x7E, 0xD0)               # SCPU regs en
emit(0x8D, 0x7A, 0xD0)               # 1MHz mode (key bit!)
# DO NOT enable turbo before FETCH
emit(0xA9, 0x03, 0x8D, 0x20, 0xD0)   # border cyan

# REU FETCH from $2A:$6C00 -> $0500 (in 1MHz mode)
emit(0xA9, 0x00, 0x8D, 0x02, 0xDF)
emit(0xA9, 0x05, 0x8D, 0x03, 0xDF)
emit(0xA9, 0x00, 0x8D, 0x04, 0xDF)
emit(0xA9, 0x6C, 0x8D, 0x05, 0xDF)
emit(0xA9, 0x2A, 0x8D, 0x06, 0xDF)
emit(0xA9, 0x00, 0x8D, 0x07, 0xDF)
emit(0xA9, 0x01, 0x8D, 0x08, 0xDF)
emit(0xA9, 0x91, 0x8D, 0x01, 0xDF)   # FETCH (in 1MHz)

# Now turbo on for long-store (mimics Doom)
emit(0x8D, 0x7B, 0xD0)               # turbo on

# Long-store $0500 -> bank $2A:$6C00
emit(0xA9, 0x00, 0x85, 0xFB)
emit(0xA9, 0x6C, 0x85, 0xFC)
emit(0xA9, 0x2A, 0x85, 0xFD)
emit(0xA9, 0x34, 0x85, 0x01)
emit(0xA0, 0x00)
emit(0xB9, 0x00, 0x05)
emit(0x97, 0xFB)
emit(0xC8)
emit(0xD0, 0xF8)
emit(0xA9, 0x35, 0x85, 0x01)

# Back to 1MHz (mimics Doom)
emit(0x8D, 0x7A, 0xD0)

# Native + 16-bit M; LDA long $2A:$6C00
emit(0x18, 0xFB)
emit(0xC2, 0x20)
emit(0xAF, 0x00, 0x6C, 0x2A)
emit(0xE2, 0x20)                     # SEP back to 8-bit M

emit(0xC9, 0x3E)
bne_pos = len(code)
emit(0xD0, 0x00)

# PASS green
emit(0xA9, 0x05, 0x8D, 0x20, 0xD0)
pass_jmp_pos = len(code)
emit(0x4C, 0x00, 0x00)

# RED
red_pos = len(code)
emit(0xA9, 0x02, 0x8D, 0x20, 0xD0)
fail_jmp_pos = len(code)
emit(0x4C, 0x00, 0x00)

bne_offset = red_pos - (bne_pos + 2)
assert -128 <= bne_offset <= 127
code[bne_pos + 1] = bne_offset & 0xFF

addr = 0x080D + pass_jmp_pos
code[pass_jmp_pos + 1] = addr & 0xFF
code[pass_jmp_pos + 2] = (addr >> 8) & 0xFF
addr = 0x080D + fail_jmp_pos
code[fail_jmp_pos + 1] = addr & 0xFF
code[fail_jmp_pos + 2] = (addr >> 8) & 0xFF

prg = bytes([0x01, 0x08]) + basic_stub + bytes(code)
with open(OUT, 'wb') as f:
    f.write(prg)
print('wrote {} ({} bytes)'.format(OUT, len(prg)))
