with open(sys.argv[1] if len(sys.argv) > 1 else 'asterix.prg', 'rb') as f:
    data = f.read()
load = data[0] | (data[1] << 8)
start = int(sys.argv[2], 16) if len(sys.argv) > 2 else 0x0820
end   = int(sys.argv[3], 16) if len(sys.argv) > 3 else 0x0894

pc = start
while pc < end:
    off = pc - load + 2
    if off < 0 or off >= len(data): break
    op = data[off]
    sz = SZ.get(op, 0)
    name = NAM.get(op, f'??{op:02X}')
    raw = data[off:off+1+sz]
    ops = raw[1:]
    opstr = ''
    if sz == 1: opstr = f'${ops[0]:02X}'
    elif sz == 2: opstr = f'${ops[1]:02X}{ops[0]:02X}'
    elif sz == 3: opstr = f'${ops[2]:02X}{ops[1]:02X}{ops[0]:02X}'
    print(f'  ${pc:04X}: {" ".join(f"{b:02x}" for b in raw):<14s} {name} {opstr}')
    pc += 1 + sz
