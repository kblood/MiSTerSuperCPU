// debug_font_4x6.sv
//
// Combinational 4x6 inline font. Inputs: glyph id (0..63), row (0..5).
// Output: 4-bit row pixels, MSB = leftmost. Synthesized as LUT cascade
// (no M10K) so the font has zero block-RAM cost.
//
// Glyph id allocation:
//    0..9   '0'..'9'
//   10..35  'A'..'Z'
//   36      ' '  (space)
//   37      ':'
//   38      '_'
//   39      '='
//   40..63  reserved (returns blank rows)

module debug_font_4x6 (
	input  logic [5:0] glyph,
	input  logic [2:0] row,
	output logic [3:0] pixels
);

	// 24 bits per glyph, packed as {row0, row1, row2, row3, row4, row5}
	// where each row is 4 bits MSB=left.
	logic [23:0] g;

	always_comb begin
		case (glyph)
			// Digits ----------------------------------------------------
			6'd0:  g = {4'b0110, 4'b1001, 4'b1011, 4'b1101, 4'b1001, 4'b0110}; // 0
			6'd1:  g = {4'b0010, 4'b0110, 4'b0010, 4'b0010, 4'b0010, 4'b0111}; // 1
			6'd2:  g = {4'b0110, 4'b1001, 4'b0010, 4'b0100, 4'b1000, 4'b1111}; // 2
			6'd3:  g = {4'b1110, 4'b0001, 4'b0110, 4'b0001, 4'b1001, 4'b0110}; // 3
			6'd4:  g = {4'b0010, 4'b0110, 4'b1010, 4'b1111, 4'b0010, 4'b0010}; // 4
			6'd5:  g = {4'b1111, 4'b1000, 4'b1110, 4'b0001, 4'b1001, 4'b0110}; // 5
			6'd6:  g = {4'b0110, 4'b1000, 4'b1110, 4'b1001, 4'b1001, 4'b0110}; // 6
			6'd7:  g = {4'b1111, 4'b0001, 4'b0010, 4'b0010, 4'b0100, 4'b0100}; // 7
			6'd8:  g = {4'b0110, 4'b1001, 4'b0110, 4'b1001, 4'b1001, 4'b0110}; // 8
			6'd9:  g = {4'b0110, 4'b1001, 4'b1001, 4'b0111, 4'b0001, 4'b0110}; // 9

			// Uppercase letters ----------------------------------------
			6'd10: g = {4'b0110, 4'b1001, 4'b1001, 4'b1111, 4'b1001, 4'b1001}; // A
			6'd11: g = {4'b1110, 4'b1001, 4'b1110, 4'b1001, 4'b1001, 4'b1110}; // B
			6'd12: g = {4'b0110, 4'b1001, 4'b1000, 4'b1000, 4'b1001, 4'b0110}; // C
			6'd13: g = {4'b1110, 4'b1001, 4'b1001, 4'b1001, 4'b1001, 4'b1110}; // D
			6'd14: g = {4'b1111, 4'b1000, 4'b1110, 4'b1000, 4'b1000, 4'b1111}; // E
			6'd15: g = {4'b1111, 4'b1000, 4'b1110, 4'b1000, 4'b1000, 4'b1000}; // F
			6'd16: g = {4'b0110, 4'b1001, 4'b1000, 4'b1011, 4'b1001, 4'b0111}; // G
			6'd17: g = {4'b1001, 4'b1001, 4'b1111, 4'b1001, 4'b1001, 4'b1001}; // H
			6'd18: g = {4'b1110, 4'b0100, 4'b0100, 4'b0100, 4'b0100, 4'b1110}; // I
			6'd19: g = {4'b0001, 4'b0001, 4'b0001, 4'b0001, 4'b1001, 4'b0110}; // J
			6'd20: g = {4'b1001, 4'b1010, 4'b1100, 4'b1100, 4'b1010, 4'b1001}; // K
			6'd21: g = {4'b1000, 4'b1000, 4'b1000, 4'b1000, 4'b1000, 4'b1111}; // L
			6'd22: g = {4'b1001, 4'b1111, 4'b1111, 4'b1001, 4'b1001, 4'b1001}; // M
			6'd23: g = {4'b1001, 4'b1101, 4'b1111, 4'b1011, 4'b1001, 4'b1001}; // N
			6'd24: g = {4'b0110, 4'b1001, 4'b1001, 4'b1001, 4'b1001, 4'b0110}; // O
			6'd25: g = {4'b1110, 4'b1001, 4'b1001, 4'b1110, 4'b1000, 4'b1000}; // P
			6'd26: g = {4'b0110, 4'b1001, 4'b1001, 4'b1001, 4'b1011, 4'b0111}; // Q
			6'd27: g = {4'b1110, 4'b1001, 4'b1001, 4'b1110, 4'b1010, 4'b1001}; // R
			6'd28: g = {4'b0111, 4'b1000, 4'b0110, 4'b0001, 4'b0001, 4'b1110}; // S
			6'd29: g = {4'b1111, 4'b0100, 4'b0100, 4'b0100, 4'b0100, 4'b0100}; // T
			6'd30: g = {4'b1001, 4'b1001, 4'b1001, 4'b1001, 4'b1001, 4'b0110}; // U
			6'd31: g = {4'b1001, 4'b1001, 4'b1001, 4'b1001, 4'b0110, 4'b0110}; // V
			6'd32: g = {4'b1001, 4'b1001, 4'b1001, 4'b1111, 4'b1111, 4'b1001}; // W
			6'd33: g = {4'b1001, 4'b1001, 4'b0110, 4'b0110, 4'b1001, 4'b1001}; // X
			6'd34: g = {4'b1001, 4'b1001, 4'b1001, 4'b0110, 4'b0100, 4'b0100}; // Y
			6'd35: g = {4'b1111, 4'b0001, 4'b0010, 4'b0100, 4'b1000, 4'b1111}; // Z

			// Punctuation ----------------------------------------------
			6'd36: g = {4'b0000, 4'b0000, 4'b0000, 4'b0000, 4'b0000, 4'b0000}; // space
			6'd37: g = {4'b0000, 4'b0010, 4'b0000, 4'b0000, 4'b0010, 4'b0000}; // :
			6'd38: g = {4'b0000, 4'b0000, 4'b0000, 4'b0000, 4'b0000, 4'b1111}; // _
			6'd39: g = {4'b0000, 4'b1111, 4'b0000, 4'b1111, 4'b0000, 4'b0000}; // =

			default: g = '0;
		endcase
	end

	always_comb begin
		case (row)
			3'd0: pixels = g[23:20];
			3'd1: pixels = g[19:16];
			3'd2: pixels = g[15:12];
			3'd3: pixels = g[11:8];
			3'd4: pixels = g[7:4];
			3'd5: pixels = g[3:0];
			default: pixels = '0;
		endcase
	end

endmodule
