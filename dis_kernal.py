def dis(start, n=60, label=''):
    if label: print(f'=== {label} ===')
    addr = start
    for _ in range(n):
        if addr>0xFFFF or addr<0xC000: break
        b = r(addr)
        ln = LENS.get(b,1)
        name = NAMES.get(b, f'?{b:02X}?')
        ops = ''
        if ln == 2:
            op = r(addr+1)
            if b in (0xD0,0xF0,0xB0,0x90,0x10,0x30,0x50,0x70,0x80):
                off = op if op < 128 else op-256
                t = (addr+2+off) & 0xFFFF
                ops = f'${op:02X}->${t:04X}'
            else:
                ops = f'${op:02X}'
        elif ln >= 3:
            lo2, hi2 = r(addr+1), r(addr+2)
            t2 = lo2 | (hi2 << 8)
            ops = f'${t2:04X}'
        hex_s = ' '.join(f'{r(addr+i):02X}' for i in range(ln))
        danger = '  <==DANGER' if '***' in name else ''
        print(f'  {addr:04X}: {hex_s:<10} {name:<18} {ops}{danger}')
        addr += ln

